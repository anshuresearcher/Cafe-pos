-- Slash POS: WhatsApp OTP challenges and verified QR guest sessions.
-- Run once in Supabase SQL Editor before deploying the matching server.js.
-- No existing POS tables or rows are modified.

CREATE TABLE IF NOT EXISTS public.qr_guest_otp_challenges (
    id UUID PRIMARY KEY,
    business_id INTEGER NOT NULL REFERENCES public.businesses(id) ON DELETE CASCADE,
    menu_token_hash TEXT NOT NULL CHECK (menu_token_hash ~ '^[a-f0-9]{64}$'),
    table_number TEXT NOT NULL,
    phone TEXT NOT NULL CHECK (phone ~ '^[0-9]{10}$'),
    provider_request_id TEXT,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0 AND attempts <= 5),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    resend_after TIMESTAMPTZ NOT NULL,
    verified_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS qr_guest_otp_lookup_idx
    ON public.qr_guest_otp_challenges (business_id, menu_token_hash, table_number, phone, created_at DESC);
CREATE INDEX IF NOT EXISTS qr_guest_otp_rate_idx
    ON public.qr_guest_otp_challenges (business_id, phone, created_at DESC);
CREATE INDEX IF NOT EXISTS qr_guest_otp_expiry_idx
    ON public.qr_guest_otp_challenges (expires_at);

CREATE TABLE IF NOT EXISTS public.qr_guest_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id INTEGER NOT NULL REFERENCES public.businesses(id) ON DELETE CASCADE,
    menu_token_hash TEXT NOT NULL CHECK (menu_token_hash ~ '^[a-f0-9]{64}$'),
    table_number TEXT NOT NULL,
    phone TEXT NOT NULL CHECK (phone ~ '^[0-9]{10}$'),
    customer_id INTEGER REFERENCES public.customers(id) ON DELETE SET NULL,
    session_token_hash TEXT NOT NULL UNIQUE CHECK (session_token_hash ~ '^[a-f0-9]{64}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_activity_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS qr_guest_session_lookup_idx
    ON public.qr_guest_sessions (session_token_hash, business_id, menu_token_hash, table_number, phone, expires_at);
CREATE INDEX IF NOT EXISTS qr_guest_session_expiry_idx
    ON public.qr_guest_sessions (expires_at);

-- These records are accessed only by the backend using its PostgreSQL connection.
-- Do not expose OTP/session data through Supabase's client-facing API roles.
ALTER TABLE public.qr_guest_otp_challenges ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.qr_guest_sessions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS qr_guest_otp_backend_only ON public.qr_guest_otp_challenges;
CREATE POLICY qr_guest_otp_backend_only ON public.qr_guest_otp_challenges
    USING (current_setting('app.system_mode', true) = 'on')
    WITH CHECK (current_setting('app.system_mode', true) = 'on');
DROP POLICY IF EXISTS qr_guest_sessions_backend_only ON public.qr_guest_sessions;
CREATE POLICY qr_guest_sessions_backend_only ON public.qr_guest_sessions
    USING (current_setting('app.system_mode', true) = 'on')
    WITH CHECK (current_setting('app.system_mode', true) = 'on');

REVOKE ALL ON public.qr_guest_otp_challenges FROM anon, authenticated;
REVOKE ALL ON public.qr_guest_sessions FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.qr_guest_otp_challenges TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.qr_guest_sessions TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.qr_guest_sessions_id_seq TO service_role;

-- The POS connects with the restricted cafe_pos_runtime role, not service_role.
-- The backend-only RLS policies above still require app.system_mode='on'.
GRANT SELECT, INSERT, UPDATE ON public.qr_guest_otp_challenges TO cafe_pos_runtime;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.qr_guest_sessions TO cafe_pos_runtime;
GRANT USAGE, SELECT ON SEQUENCE public.qr_guest_sessions_id_seq TO cafe_pos_runtime;

